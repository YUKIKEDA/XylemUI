namespace XylemUI.Text;

/// <summary>
/// The slant of a font, as CSS's <c>font-style</c>.
/// </summary>
public enum FontSlant
{
    /// <summary>Upright.</summary>
    Normal,

    /// <summary>The family's italic face.</summary>
    Italic,

    /// <summary>A slanted face of the upright design.</summary>
    Oblique,
}
