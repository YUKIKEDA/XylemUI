using System.Globalization;
using System.Text;

namespace XylemUI.Tools.FluentIcons;

/// <summary>
/// Writes <c>FluentIcons.g.cs</c>: a property for each icon of each font, written with an expression body so that NativeAOT drops
/// the getters an app does not call; an initializer would make a static constructor build every one (spike #716).
/// </summary>
internal static class Generator
{
    /// <summary>
    /// Writes the properties of both fonts.
    /// </summary>
    /// <param name="directory">The Fluent directory.</param>
    /// <param name="output">The file to write.</param>
    public static void Write(string directory, string output)
    {
        var code = new StringBuilder();
        _ = code.Append(
            """
            // <auto-generated>
            // Generated by tools/FluentIconsTool from FluentSystemIcons-Regular.json and FluentSystemIcons-Filled.json of Fluent UI
            // System Icons 1.1.344 (vendor/versions.lock). Do not edit: run `FluentIconsTool generate` again.
            // </auto-generated>
            using XylemUI.Primitives;

            namespace XylemUI.Theme.Fluent;

            /// <summary>
            /// The glyphs of Fluent UI System Icons (MIT), Regular and Filled, each drawn for its size (design §5.0.4, "Icons"). The
            /// first glyph an app reads registers the font with <see cref="AppFonts"/>; the build keeps only the glyphs an app reads.
            /// </summary>
            public static partial class FluentIcons
            {

            """
        );
        foreach (string style in Icons.Styles)
        {
            Icons icons = Icons.Read(directory, style);
            foreach (Icon icon in icons.List)
            {
                string summary = string.Create(
                    CultureInfo.InvariantCulture,
                    $"    /// <summary>Gets <c>{icon.Name}</c> (U+{icon.CodePoint:X4}), drawn for {icon.Size} px.</summary>\n"
                );
                string property = string.Create(
                    CultureInfo.InvariantCulture,
                    $"    public static IconGlyph {icon.Property} => new(FluentIconFonts.{style}, 0x{icon.CodePoint:X4}, {icon.Size});\n\n"
                );
                _ = code.Append(summary).Append(property);
            }
        }

        _ = code.Append("}\n");
        File.WriteAllText(output, code.ToString().ReplaceLineEndings("\n"), new UTF8Encoding(false));
    }
}
